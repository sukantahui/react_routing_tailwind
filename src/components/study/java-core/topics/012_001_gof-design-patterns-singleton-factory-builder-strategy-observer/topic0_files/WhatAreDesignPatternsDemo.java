public class WhatAreDesignPatternsDemo {

    public static void main(String[] args) {
        System.out.println("==========================================================================");
        System.out.println(" TOPIC 0: WHAT ARE DESIGN PATTERNS - BARRACKPORE ACADEMY");
        System.out.println("==========================================================================\n");

        System.out.println(">>> 1. DEFINITION OF A DESIGN PATTERN:");
        System.out.println("  - A formalized best practice / reusable solution to a commonly occurring problem in software design.");
        System.out.println("  - Published in 1994 by the 'Gang of Four' (Erich Gamma, Richard Helm, Ralph Johnson, John Vlissides).\n");

        System.out.println(">>> 2. CORE ELEMENTS OF A PATTERN:");
        System.out.println("  - Pattern Name : Creates a shared architectural vocabulary among engineers (e.g. 'Use an Observer here').");
        System.out.println("  - Problem      : Describes when to apply the pattern.");
        System.out.println("  - Solution     : Describes elements, relationships, responsibilities, and collaborations.");
        System.out.println("  - Consequences : The trade-offs and results of applying the pattern.\n");

        System.out.println(">>> 3. KEY ARCHITECTURAL PRINCIPLES EMBODIED:");
        System.out.println("  - Program to an interface, not an implementation.");
        System.out.println("  - Favor object composition over class inheritance.");
        System.out.println("  - Encapsulate what varies.");

        System.out.println("\n==========================================================================");
    }
}
