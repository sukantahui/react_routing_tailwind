public class StringArraySortDemo {
    public static void main(String[] args) {
        System.out.println("Topic 2: Sorting String Array Alphabetically (Bubble / Selection Sort)");
        String[] cities = {"Barrackpore", "Shyamnagar", "Ichapur", "Naihati"};
        for (String c : cities) {
            System.out.println("City: " + c);
        }
    }
}
