public class CaseInsensitiveStringArrayDemo {
    public static void main(String[] args) {
        System.out.println("Topic 3: Case Insensitive Comparison in String Array");
        String[] cities = {"Barrackpore", "Shyamnagar", "Ichapur", "Naihati"};
        for (String c : cities) {
            System.out.println("City: " + c);
        }
    }
}
